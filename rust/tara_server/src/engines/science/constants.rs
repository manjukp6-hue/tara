//! Fundamental physical and astronomical constants for ScienceEngine.

/// Speed of light in vacuum (m/s)
pub const SPEED_OF_LIGHT: f64 = 299_792_458.0;

/// Newtonian constant of gravitation (N m^2 / kg^2)
pub const GRAVITATIONAL_CONSTANT: f64 = 6.67430e-11;

/// Planck constant (J s)
pub const PLANCK_CONSTANT: f64 = 6.62607015e-34;

/// Reduced Planck constant h-bar (J s)
pub const H_BAR: f64 = 1.054571817e-34;

/// Boltzmann constant (J / K)
pub const BOLTZMANN_CONSTANT: f64 = 1.380649e-23;

/// Avogadro constant (mol^-1)
pub const AVOGADRO_CONSTANT: f64 = 6.02214076e23;

/// Elementary electric charge (C)
pub const ELEMENTARY_CHARGE: f64 = 1.602176634e-19;

/// Universal gas constant (J / (mol K))
pub const GAS_CONSTANT: f64 = 8.314462618;

/// Standard acceleration due to gravity on Earth (m/s^2)
pub const STANDARD_GRAVITY: f64 = 9.80665;

/// Stefan-Boltzmann constant (W / (m^2 K^4))
pub const STEFAN_BOLTZMANN: f64 = 5.670374419e-8;

/// Vacuum electric permittivity epsilon_0 (F / m)
pub const VACUUM_PERMITTIVITY: f64 = 8.8541878128e-12;

/// Vacuum magnetic permeability mu_0 (N / A^2)
pub const VACUUM_PERMEABILITY: f64 = 1.25663706212e-6;

/// Mass of electron (kg)
pub const ELECTRON_MASS: f64 = 9.1093837015e-31;

/// Mass of proton (kg)
pub const PROTON_MASS: f64 = 1.67262192369e-27;

/// Mass of neutron (kg)
pub const NEUTRON_MASS: f64 = 1.67492749804e-27;

/// Mass of Earth (kg)
pub const EARTH_MASS: f64 = 5.9722e24;

/// Mean radius of Earth (m)
pub const EARTH_RADIUS: f64 = 6.371e6;

/// Mass of Sun (kg)
pub const SOLAR_MASS: f64 = 1.98847e30;

/// Astronomical Unit (m)
pub const ASTRONOMICAL_UNIT: f64 = 1.495978707e11;

/// Light year (m)
pub const LIGHT_YEAR: f64 = 9.4607304725808e15;

/// Parsec (m)
pub const PARSEC: f64 = 3.08567758149137e16;

/// Hubble constant (km/s / Mpc)
pub const HUBBLE_CONSTANT: f64 = 70.0;
